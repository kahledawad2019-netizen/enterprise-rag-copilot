   core.customers
   -------------------------------------------------------------------------- */
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_customers_tenant_status')
CREATE INDEX IX_customers_tenant_status
    ON core.customers (tenant_id, status)
    INCLUDE (customer_code, display_name, segment, region, signup_date, churn_date);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_customers_churn_date')
CREATE INDEX IX_customers_churn_date
    ON core.customers (churn_date)
    WHERE churn_date IS NOT NULL;   -- filtered: only churned rows are ever scanned here

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_customers_display_name')
