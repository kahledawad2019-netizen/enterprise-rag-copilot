/* Overdue invoices are queried constantly by the risk views, and they are a
   small fraction of the table: a filtered index keeps that lookup tiny. */
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_invoices_overdue')
CREATE INDEX IX_invoices_overdue
    ON billing.invoices (customer_id, due_date)
    INCLUDE (total_amount, amount_paid)
    WHERE status IN ('open', 'overdue', 'partial');

